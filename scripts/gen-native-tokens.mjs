#!/usr/bin/env node
// Generates mobile/src/theme/tokens.generated.ts from src/styles/tokens.css, so the native app and the web share
// one palette. tests/unit/native-tokens.test.ts fails when the committed file drifts from this output.
// Usage: node scripts/gen-native-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ACCENT_KEYS = ["accent", "accent-hover", "accent2", "accent2-hover", "accent-soft", "heat-1", "heat-2", "heat-3", "heat-4"];

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** `--name: value;` pairs of a declaration block (comments stripped), in order. */
function declarations(body) {
  const out = [];
  for (const m of body.replace(/\/\*[\s\S]*?\*\//g, "").matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) out.push([m[1], m[2].trim()]);
  return out;
}

function value(raw, vars) {
  const v = raw.trim();
  const ref = /^var\(--([\w-]+)\)$/.exec(v);
  if (ref) {
    if (!(ref[1] in vars)) throw new Error(`unresolved var(--${ref[1]})`);
    return vars[ref[1]];
  }
  const rgb = /^rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*\/\s*([\d.]+)\s*\)$/.exec(v);
  if (rgb) return `rgba(${rgb[1]},${rgb[2]},${rgb[3]},${rgb[4]})`;
  return v;
}

function block(css, re, what) {
  const m = re.exec(css);
  if (!m) throw new Error(`tokens.css: ${what} block not found`);
  return m[1];
}

/**
 * @typedef {Record<string, string>} Palette
 * @typedef {{ light: Palette, dark: Palette }} Accent
 * @param {string} css
 * @returns {{ light: Palette, dark: Palette, accents: Record<string, Accent>, radius: Record<string, number>, space: Record<string, number> }}
 */
export function parseTokens(css) {
  const theme = declarations(block(css, /@theme\s*\{([\s\S]*?)\n\}/, "@theme"));
  /** @type {Palette} */
  const light = {};
  /** @type {Record<string, number>} */
  const radius = {};
  /** @type {Palette} */
  const raw = {};
  for (const [name, v] of theme) {
    if (name.startsWith("color-") && name !== "color-*") {
      raw[name.slice(6)] = value(v, raw);
      light[camel(name.slice(6))] = raw[name.slice(6)];
    } else if (name.startsWith("radius-")) radius[name.slice(7)] = parseInt(v, 10);
  }

  const rootBlocks = [...css.matchAll(/^:root\s*\{([\s\S]*?)\n\}/gm)].map((m) => declarations(m[1]));
  /** @type {Record<string, number>} */
  const space = {};
  for (const decls of rootBlocks) {
    for (const [name, v] of decls) {
      if (name.startsWith("space-")) space[name.slice(6)] = parseInt(v, 10);
      // habit identity colors only: the -soft variants are color-mix() and the app derives them
      else if (/^habit-[a-z]+$/.test(name) && name !== "habit-on" && /^#/.test(v)) light[camel(name)] = v;
      else if (name === "habit-on") light.habitOn = v;
    }
  }

  const darkDecls = declarations(block(css, /^:root\[data-theme="dark"\]\s*\{([\s\S]*?)\n\}/m, "dark theme"));
  const dark = { ...light };
  for (const [name, v] of darkDecls) {
    if (name.startsWith("color-")) dark[camel(name.slice(6))] = value(v, {});
    else if (/^habit-[a-z]+$/.test(name)) dark[camel(name)] = v;
  }

  /** @type {Record<string, Accent>} */
  const accents = {};
  for (const m of css.matchAll(/^\[data-color="([a-z]+)"\]\s*\{([\s\S]*?)\n\}/gm)) {
    const pal = Object.fromEntries(declarations(m[2]));
    const pick = (prefix) => Object.fromEntries(ACCENT_KEYS.map((k) => {
      const v = pal[`${prefix}${k}`];
      if (v === undefined) throw new Error(`[data-color="${m[1]}"]: --${prefix}${k} missing`);
      return [camel(k), v];
    }));
    accents[m[1]] = { light: pick("pal-"), dark: pick("pal-dark-") };
  }
  return { light, dark, accents, radius, space };
}

/** @param {string} css */
export function generateTokensSource(css) {
  const t = parseTokens(css);
  const json = (/** @type {unknown} */ o) => JSON.stringify(o, null, 2);
  return `// GENERATED by scripts/gen-native-tokens.mjs from src/styles/tokens.css. Do not edit by hand.
// tests/unit/native-tokens.test.ts fails when this file drifts from the CSS.

export const lightTokens = ${json(t.light)} as const;

export const darkTokens = ${json(t.dark)} as const;

export const accents = ${json(t.accents)} as const;

export const radius = ${json(t.radius)} as const;

export const space = ${json(t.space)} as const;

export type AccentName = keyof typeof accents;
export type ThemeTokens = { [K in keyof typeof lightTokens]: string };
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = readFileSync(new URL("../src/styles/tokens.css", import.meta.url), "utf8");
  writeFileSync(new URL("../mobile/src/theme/tokens.generated.ts", import.meta.url), generateTokensSource(css));
}
